function renderBodyItems(items) {
  if (!items || !items.length) return '';
  return items.map(item => {
    if (item.type === 'p') {
      return `<p class="passage-text">${item.text}</p>`;
    }
    if (item.type === 'tbl') {
      const rowsHtml = item.rows.map((row, rIdx) => {
        const tag = rIdx === 0 ? 'th' : 'td';
        return `<tr>${row.map(c => `<${tag}>${c}</${tag}>`).join('')}</tr>`;
      }).join('');
      return `<div class="table-wrap"><table class="data-table">${rowsHtml}</table></div>`;
    }
    return '';
  }).join('');
}

function renderExam(code) {
  const exam = EXAMS_DATA[code];
  if (!exam) return;

  document.querySelectorAll('.code-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.code === code);
  });
  document.getElementById('current-code-label').textContent = `Mã đề ${code}`;

  // Phần I
  const p1Html = exam.part1.map(q => {
    const optsHtml = q.options.map(opt => `
      <div class="option-item ${opt.correct ? 'correct-answer' : ''}">
        ${opt.text}
      </div>
    `).join('');
    return `
      <div class="question-card">
        <div class="question-title">${q.question}</div>
        <div class="options-grid">${optsHtml}</div>
        <div class="citation-box">
          <div><strong>Giải thích:</strong> ${q.note}</div>
          <div><strong>Nguồn kiểm tra:</strong> <a href="${q.source_url}" target="_blank" rel="noopener noreferrer">${q.source_title} (${q.source_url})</a></div>
        </div>
      </div>
    `;
  }).join('');
  document.getElementById('part1-container').innerHTML = p1Html;

  // Phần II
  const p2Html = exam.part2.map(q => {
    const stHtml = q.statements.map(st => `
      <div class="tf-item ${st.correct ? 'correct-answer' : ''}">
        <div class="tf-Header">
          <span class="tf-text">${st.text}</span>
          <span class="tf-badges">
            <span class="tf-badge ${st.correct ? 'correct-answer' : ''}">Đúng</span>
            <span class="tf-badge ${!st.correct ? 'correct-answer' : ''}">Sai</span>
          </span>
        </div>
        <div class="tf-explain">→ ${st.explain}</div>
      </div>
    `).join('');
    return `
      <div class="question-card">
        <div class="question-title">${q.question}</div>
        <div class="question-body">${renderBodyItems(q.body)}</div>
        <div class="tf-list">${stHtml}</div>
        <div class="citation-box">
          <div><strong>Nguồn kiểm tra:</strong> <a href="${q.source_url}" target="_blank" rel="noopener noreferrer">${q.source_title} (${q.source_url})</a></div>
        </div>
      </div>
    `;
  }).join('');
  document.getElementById('part2-container').innerHTML = p2Html;

  // Phần III
  const p3Html = exam.part3.map(q => `
    <div class="question-card">
      <div class="question-title">${q.question}</div>
      <div class="question-body">${renderBodyItems(q.body)}</div>
      <div class="short-answer-box correct-answer">
        <strong>Đáp án: ${q.answer}</strong>
      </div>
      <div class="citation-box">
        <div><strong>Cách giải:</strong> ${q.explanation}</div>
        <div><strong>Nguồn kiểm tra:</strong> <a href="${q.source_url}" target="_blank" rel="noopener noreferrer">${q.source_title} (${q.source_url})</a></div>
      </div>
    </div>
  `).join('');
  document.getElementById('part3-container').innerHTML = p3Html;
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.code-btn').forEach(btn => {
    btn.addEventListener('click', () => renderExam(btn.dataset.code));
  });
  renderExam('1101');
});
